"""Pack one area into data/<id>/bundle.js and list every packed area in data/areas.js,
so index.html works by double-click (file://) with no network. Browsers block fetch() and WebGL images from
file:// pages, so the images go in as data URLs and each area is one classic script.

Usage: python -I scripts/team8_bundle.py data/<id>
"""
import base64, glob, json, os, sys

DATA = sys.argv[1].rstrip("/\\")
ROOT = os.path.dirname(DATA)
meta = json.load(open(os.path.join(DATA, "terrain_meta.json"), encoding="utf-8"))
sim = json.load(open(os.path.join(DATA, "sim.json"), encoding="utf-8"))


def durl(name, mime):
    with open(os.path.join(DATA, name), "rb") as f:
        return f"data:{mime};base64," + base64.b64encode(f.read()).decode("ascii")


img = dict(terrain=durl(meta["files"]["terrain_rgb_mesh"], "image/png"), color=durl(meta["files"]["topo"], "image/jpeg"),
           slope=durl(meta["files"]["slope"], "image/png"), prob=[durl(s["png"], "image/png") for s in sim["stages"]])
if os.path.exists(os.path.join(DATA, "nogo.png")):   # water and cliffs for the route planner in the browser (team8_masks.py)
    img["nogo"] = durl("nogo.png", "image/png")
out = os.path.join(DATA, "bundle.js")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* generated by scripts/team8_bundle.py, do not edit */\n")
    f.write("window.TEAM8 = ")
    json.dump(dict(meta=meta, sim=sim, img=img), f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print(out, round(os.path.getsize(out) / 1e6, 2), "MB")

areas = []
for mp in sorted(glob.glob(os.path.join(ROOT, "*", "terrain_meta.json"))):
    d = os.path.dirname(mp)
    if not os.path.exists(os.path.join(d, "bundle.js")):
        continue
    m = json.load(open(mp, encoding="utf-8"))
    areas.append(dict(id=m["id"], name=m["name"], region=m["region"], dem=m["dem"]["label"], km2=m["area_km2"],
                      mb=round(os.path.getsize(os.path.join(d, "bundle.js")) / 1e6, 1)))
areas.sort(key=lambda a: (a["id"] != "moran", a["name"]))
with open(os.path.join(ROOT, "areas.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("/* generated by scripts/team8_bundle.py: the areas index.html can open */\nwindow.TEAM8_AREAS = ")
    json.dump(areas, f, ensure_ascii=False, indent=1)
    f.write(";\n")
print("areas", [a["id"] for a in areas])
