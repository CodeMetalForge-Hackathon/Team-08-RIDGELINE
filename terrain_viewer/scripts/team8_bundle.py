"""Pack the viewer data into data/bundle.js so index.html works by double-click (file://) with no network.

Browsers block fetch() and WebGL images from file:// pages, so the images go in as data URLs.
Usage: python -I team8_bundle.py <data_dir> [mesh: 10m|5m]
"""
import sys, os, json, base64

DATA = sys.argv[1]
MESH = sys.argv[2] if len(sys.argv) > 2 else "10m"
meta = json.load(open(os.path.join(DATA, "terrain_meta.json"), encoding="utf-8"))
sim = json.load(open(os.path.join(DATA, "sim.json"), encoding="utf-8"))


def durl(name, mime):
    with open(os.path.join(DATA, name), "rb") as f:
        return f"data:{mime};base64," + base64.b64encode(f.read()).decode("ascii")


img = dict(
    terrain=durl(meta["files"][f"terrain_rgb_{MESH}"], "image/png"),
    color=durl(meta["files"]["color_5m_jpg"], "image/jpeg"),
    prob=[durl(s["png"], "image/png") for s in sim["stages"]],
)
out = os.path.join(DATA, "bundle.js")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* generated by scripts/team8_bundle.py, do not edit */\n")
    f.write("window.TEAM8 = ")
    json.dump(dict(mesh=MESH, meta=meta, sim=sim, img=img), f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print("bundle.js", round(os.path.getsize(out) / 1e6, 2), "MB, mesh", MESH)
