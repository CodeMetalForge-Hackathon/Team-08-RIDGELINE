"""Embed the UI fonts as data URLs so the viewer keeps its look offline and from file://.

Chrome refuses font files loaded from file:// (fonts need CORS), so the woff2 bytes go inside the CSS.
Fonts: Noto Sans JP (latin subset, 400 600 700) for text, B612 Mono (latin, 400 700) for numbers.
B612 was drawn for Airbus cockpit displays, which suits a pilot's navigation HUD. Both are SIL OFL 1.1.

Get the packages first (in an empty folder):  npm pack @fontsource/noto-sans-jp@5.3.1 @fontsource/b612-mono@5.3.0
and extract each .tgz into a folder named like the file without .tgz.
Usage: python -I team8_fonts.py <folder_with_extracted_packages> <out_dir, e.g. lib/fonts>
"""
import sys, os, base64, shutil

SRC, OUT = sys.argv[1], sys.argv[2]
NOTO = os.path.join(SRC, "fontsource-noto-sans-jp-5.3.1", "package")
B612 = os.path.join(SRC, "fontsource-b612-mono-5.3.0", "package")
FACES = [("Noto Sans JP", w, os.path.join(NOTO, "files", f"noto-sans-jp-latin-{w}-normal.woff2")) for w in (400, 600, 700)]
FACES += [("B612 Mono", w, os.path.join(B612, "files", f"b612-mono-latin-{w}-normal.woff2")) for w in (400, 700)]

os.makedirs(OUT, exist_ok=True)
css = ["/* generated by scripts/team8_fonts.py, do not edit. Noto Sans JP and B612 Mono, SIL OFL 1.1 (see the OFL files here) */"]
for family, weight, path in FACES:
    with open(path, "rb") as f:
        b64 = base64.b64encode(f.read()).decode("ascii")
    css.append(f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight};font-display:swap;"
               f"src:url(data:font/woff2;base64,{b64}) format('woff2')}}")
with open(os.path.join(OUT, "fonts.css"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(css) + "\n")
shutil.copyfile(os.path.join(NOTO, "LICENSE"), os.path.join(OUT, "OFL-NotoSansJP.txt"))
shutil.copyfile(os.path.join(B612, "LICENSE"), os.path.join(OUT, "OFL-B612Mono.txt"))
print("fonts.css", round(os.path.getsize(os.path.join(OUT, "fonts.css")) / 1e3, 1), "kB")
